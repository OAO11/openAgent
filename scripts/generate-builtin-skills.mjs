// Rebuild embedded resources from the reviewed, local catalog. No network access.
import { readFile, readdir, writeFile } from "node:fs/promises";
import { resolve, relative } from "node:path";
import { fileURLToPath } from "node:url";
const root = fileURLToPath(new URL("../crates/agent-gui/src-tauri/prompt/skills/", import.meta.url));
const output = resolve(root, "../../src/services/skills/builtin_catalog.rs");
const catalog = JSON.parse(await readFile(resolve(root, "catalog.json"), "utf8"));
async function files(dir) {
  const result = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    if (entry.isSymbolicLink()) throw new Error(`Symlink in built-in skill: ${entry.name}`);
    const path = resolve(dir, entry.name);
    if (entry.isDirectory()) result.push(...await files(path));
    else if (entry.isFile()) result.push(path);
  }
  return result.sort();
}
const lines = ["// Generated by scripts/generate-builtin-skills.mjs; do not edit by hand.", "use super::{BuiltinSkill, BuiltinSkillFile};", "", "pub(super) const CURATED_AGENT_SKILLS: &[BuiltinSkill] = &["];
for (const skill of catalog.skills) {
  if (!/^openagent-[a-z0-9-]+$/.test(skill.name)) throw new Error("Invalid skill name");
  const dir = resolve(root, skill.name);
  const marker = JSON.parse(await readFile(resolve(dir, "_openagent_builtin.json"), "utf8"));
  if (marker.skill !== skill.name || marker.owner !== "openAgent") throw new Error("Invalid ownership marker");
  lines.push("    BuiltinSkill {", `        name: "${skill.name}",`, "        files: &[");
  for (const path of await files(dir)) {
    const rel = relative(dir, path).replaceAll("\\", "/");
    // Validate UTF-8 before Rust include_str! and prevent unreviewed files entering the bundle.
    new TextDecoder("utf-8", { fatal: true }).decode(await readFile(path));
    lines.push("            BuiltinSkillFile {", `                path: "${rel}",`, `                content: include_str!("../../../prompt/skills/${skill.name}/${rel}"),`, "            },");
  }
  lines.push("        ],", `        ownership_marker: Some(("_openagent_builtin.json", include_str!("../../../prompt/skills/${skill.name}/_openagent_builtin.json"))),`, "    },");
}
lines.push("];", "");
const content = lines.join("\n");
if (process.argv.includes("--check")) {
  if (await readFile(output, "utf8") !== content) throw new Error("Built-in catalog is stale; run node scripts/generate-builtin-skills.mjs");
} else {
  await writeFile(output, content);
}
console.log(`Verified ${catalog.skills.length} embedded development skills.`);
