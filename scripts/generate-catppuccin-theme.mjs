// Regenerate after updating the pinned palette; no runtime palette dependency is required.
import { readFileSync, writeFileSync } from 'node:fs';
const palettes = JSON.parse(readFileSync(new URL('../crates/agent-ui/src/lib/appearance/catppuccin.json', import.meta.url), 'utf8'));
const hsl = (hex) => {
  const [r, g, b] = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255);
  const max = Math.max(r, g, b), min = Math.min(r, g, b), d = max - min, l = (max + min) / 2;
  const s = d === 0 ? 0 : d / (1 - Math.abs(2 * l - 1));
  const h = d === 0 ? 0 : (max === r ? ((g - b) / d + 6) % 6 : max === g ? (b - r) / d + 2 : (r - g) / d + 4) * 60;
  return `${h.toFixed(4)} ${(s * 100).toFixed(4)}% ${(l * 100).toFixed(4)}%`;
};
const blend = (a, b, amount) => '#' + [1, 3, 5].map((i) => Math.round(parseInt(a.slice(i, i + 2), 16) * amount + parseInt(b.slice(i, i + 2), 16) * (1 - amount)).toString(16).padStart(2, '0')).join('');
const block = (selector, tokens) => `${selector} {\n${Object.entries(tokens).map(([key, value]) => `  --${key}: ${value};`).join('\n')}\n}\n`;
let css = `/* Generated by scripts/generate-catppuccin-theme.mjs from Catppuccin 1.8.0.\n * Copyright (c) 2021 Catppuccin, MIT; see public/third-party/catppuccin-LICENSE.txt.\n * Unlayered to also override the boot shell and xterm's unlayered tokens. */\n\n`;
for (const [flavor, mode] of [['latte', 'light'], ['mocha', 'dark']]) {
  const p = palettes[flavor], dark = mode === 'dark';
  const selector = ':root[data-color-theme="catppuccin"]' + (dark ? '.dark' : '');
  const map = {
    background: 'base', foreground: 'text', card: 'base', 'card-foreground': 'text',
    popover: 'mantle', 'popover-foreground': 'text', primary: 'mauve', 'primary-foreground': dark ? 'crust' : 'base',
    secondary: 'surface0', 'secondary-foreground': 'text', muted: 'mantle', 'muted-foreground': 'subtext1',
    'settings-rail': 'crust', 'settings-tile': 'mantle', 'settings-tile-hover': 'surface0', 'settings-active': 'surface1',
    'control-surface': 'base', 'segmented-track': 'surface0', 'segmented-selected': dark ? 'surface2' : 'base',
    accent: 'surface0', 'accent-foreground': 'text', border: 'surface1', input: 'surface1', ring: 'mauve',
    'sidebar-bg': 'mantle', 'hub-canvas': 'crust', 'chip-bg': 'surface0', 'chip-bg-hover': 'surface1', 'send-disabled-bg': 'surface0',
    'chat-user-bg': 'surface0', 'chat-user-fg': 'text', 'chat-assistant-bg': 'base', 'chat-assistant-fg': 'text',
    'chat-tool-bg': 'base', 'chat-tool-border': 'surface1', 'chat-thinking-bg': 'mantle', 'chat-thinking-border': 'surface1',
    'chat-success': 'green', 'chat-error': 'red', 'chat-running': 'mauve',
    'tool-bash-accent': 'green', 'tool-file-accent': 'blue', 'tool-search-accent': 'yellow', 'tool-list-accent': 'mauve',
    'checkpoint-accent': 'subtext1', 'checkpoint-icon-bg': 'surface0', 'checkpoint-icon-fg': 'text',
  };
  const tokens = Object.fromEntries(Object.entries(map).map(([key, color]) => [key, hsl(p[color])]));
  Object.assign(tokens, {
    'tool-card-bg': `${hsl(p.mantle)} / 0.85`, 'tool-card-border': `${hsl(p.surface2)} / 0.5`,
    'checkpoint-bg': `${hsl(p.mantle)} / 0.85`, 'checkpoint-border': `${hsl(p.surface2)} / 0.5`,
  });
  for (const [status, color] of [['destructive', 'red'], ['success', 'green'], ['warning', 'yellow'], ['info', 'blue']]) {
    // Light status text needs a deeper shade for normal-size text on pale surfaces.
    tokens[status] = dark ? p[color] : blend(p[color], p.text, 0.3);
    tokens[`${status}-foreground`] = dark ? p.crust : p.base;
    tokens[`${status}-surface`] = blend(p[color], p.base, dark ? 0.12 : 0.06);
  }
  Object.assign(tokens, {
    'warning-tint': p.yellow, 'control-checked': p.mauve, 'control-thumb': dark ? p.crust : p.base,
    'search-highlight': `${p.yellow}40`, 'drop-indicator': p.mauve,
    compaction: p.mauve, 'compaction-icon': p.mauve, 'compaction-foreground': p.mauve,
    overlay: '#00000066', 'surface-subtle': `${p.text}08`, glass: `${p.mantle}e6`,
    'glass-border': `${p.surface2}60`, 'glass-border-strong': p.surface2,
    'glass-fill': `${p.surface0}80`, 'glass-highlight': `${p.text}12`,
    'media-frame': p.mantle, 'media-canvas': p.crust,
    'ui-color-1677ff': p.blue,
  });
  css += block(selector, tokens) + '\n';
}
// Both terminal modes are needed, even when a terminal explicitly requests the other mode.
const terminalTokens = {};
for (const [flavor, mode] of [['latte', 'light'], ['mocha', 'dark']]) {
  const p = palettes[flavor];
  const colors = {
    background: p.base, foreground: p.text, cursor: p.rosewater, 'cursor-accent': p.base,
    'selection-background': p.surface2, 'selection-inactive-background': p.surface1,
    'scrollbar-slider-background': `${p.overlay0}40`, 'scrollbar-slider-hover-background': `${p.overlay0}70`,
    'scrollbar-slider-active-background': `${p.overlay0}a0`, 'overview-ruler-border': '#00000000',
    black: p.surface1, red: p.red, green: p.green, yellow: p.yellow, blue: p.blue, magenta: p.pink, cyan: p.teal, white: p.subtext1,
    'bright-black': p.surface2, 'bright-red': p.red, 'bright-green': p.green, 'bright-yellow': p.yellow,
    'bright-blue': p.blue, 'bright-magenta': p.pink, 'bright-cyan': p.teal, 'bright-white': p.text,
  };
  for (const [key, value] of Object.entries(colors)) terminalTokens[`terminal-${mode}-${key}`] = value;
}
css += block(':root[data-color-theme="catppuccin"]', terminalTokens);
writeFileSync(new URL('../crates/agent-ui/src/styles/catppuccin.css', import.meta.url), css);
