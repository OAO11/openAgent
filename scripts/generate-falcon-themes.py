from pathlib import Path

REVISION = "c3ddba2d8c71137e5191033df8e882b2936f8f7d"
ROOT = Path(__file__).resolve().parent.parent
SOURCE = Path(sys.argv[1]).resolve()
RESOURCES = SOURCE / "src/main/resources"
NAMES = {
    "green": "浅绿", "green-contrast": "高对比绿", "celadon": "青瓷",
    "bean-green": "豆绿", "grey": "浅灰", "pink": "樱粉", "yellow": "暖黄", "buff": "米杏",
    "dark": "经典深色", "dark-darcula": "Darcula", "dark-green": "深青绿",
    "dark-blue": "深海蓝", "dark-violet": "暗紫", "dark-coffee": "暖咖啡",
}

def hexcolor(value):
    if not value:
        return None
    value = value.strip().lstrip("#")
    if not re.fullmatch(r"[0-9a-fA-F]{6}", value):
        raise ValueError(f"Expected opaque RGB color, got {value!r}")
    return "#" + value.lower()

def blend(a, b, amount):
    return "#" + "".join(f"{round(int(a[i:i+2],16)*amount+int(b[i:i+2],16)*(1-amount)):02x}" for i in (1,3,5))

def luminance(color):
    rgb = [int(color[i:i+2],16)/255 for i in (1,3,5)]
    return sum((c/12.92 if c <= .04045 else ((c+.055)/1.055)**2.4)*w for c,w in zip(rgb,(.2126,.7152,.0722)))

def contrast(a,b):
    hi,lo = sorted((luminance(a),luminance(b)), reverse=True)
    return (hi+.05)/(lo+.05)

def readable(fg,bg,minimum=4.5):
    if contrast(fg,bg)>=minimum:
        return fg
    target = max(("#000000", "#ffffff"),key=lambda c:contrast(c,bg))
    for step in range(1,101):
        result=blend(fg,target,1-step/100)
        if contrast(result,bg)>=minimum:
            return result
    return target

def hsl(color):
    h,l,s=colorsys.rgb_to_hls(*(int(color[i:i+2],16)/255 for i in (1,3,5)))
    return f"{h*360:.4f} {s*100:.4f}% {l*100:.4f}%"

def block(selector,tokens):
    return selector+" {\n"+"".join(f"  --{k}: {v};\n" for k,v in tokens.items())+"}\n"

catalog=[]
palettes={}
source_hashes={}
css=["/* Generated by scripts/generate-falcon-themes.py. Falcon MIT license is bundled in public/third-party. */\n"]
boot_css=[]
files=sorted(RESOURCES.glob("themes/**/*.theme.json"))
assert len(files)==28, "Pinned source must contain exactly 28 Falcon themes"
for file in files:
    data=json.loads(file.read_text(encoding="utf-8"))
    slug=file.name.removesuffix(".theme.json")
    islands=slug.startswith("islands-")
    key=slug.removeprefix("islands-")
    theme_id="falcon-"+slug
    mode="dark" if data["dark"] else "light"
    dark=mode=="dark"
    scheme_path=(RESOURCES/data["editorScheme"].lstrip("/")).resolve()
    assert scheme_path.is_relative_to(RESOURCES.resolve())
    tree=ET.parse(scheme_path).getroot()
    colors={o.get("name"):o.get("value") for o in tree.findall("./colors/option")}
    attrs={o.get("name"):{v.get("name"):v.get("value") for v in o.findall("./value/option")} for o in tree.findall("./attributes/option")}
    raw=data["colors"]
    color=lambda name,fallback:hexcolor(raw.get(name)) or fallback
    bg=color("primaryBackground",color("editorBackground","#ffffff"))
    fg=readable(color("primaryForeground","#bbbbbb" if dark else "#222222"),bg)
    accent=color("accentColor",fg)
    rail=color("mainBackground",color("secondaryBackground",color("sidePanelBackground",bg)))
    # Ensure one foreground remains readable on every UI surface, including selected rows.
    hover=color("hoverBackground",blend(fg,bg,.10))
    selection=color("selectionBackground",hover)
    for _ in range(3):
        for surface in (bg,rail,hover,selection):
            fg=readable(fg,surface)
    border=color("borderColor",blend(fg,bg,.2))
    muted=readable(blend(fg,bg,.72),bg)
    primary_text=max(("#ffffff","#111111"),key=lambda c:contrast(c,accent))
    syntax={}
    for name,attribute in {"comment":"DEFAULT_LINE_COMMENT","keyword":"DEFAULT_KEYWORD","string":"DEFAULT_STRING","number":"DEFAULT_NUMBER","type":"DEFAULT_CLASS_NAME","function":"DEFAULT_FUNCTION_DECLARATION","variable":"DEFAULT_LOCAL_VARIABLE","operator":"DEFAULT_OPERATION_SIGN","attribute":"DEFAULT_ATTRIBUTE","constant":"DEFAULT_CONSTANT"}.items():
        syntax[name]=hexcolor(attrs.get(attribute,{}).get("FOREGROUND")) or accent
    editor_bg=hexcolor(colors.get("BACKGROUND")) or bg
    editor_fg=readable(hexcolor(attrs.get("TEXT",{}).get("FOREGROUND")) or fg,editor_bg)
    syntax={name:readable(value,editor_bg,3) for name,value in syntax.items()}
    editor={"background":editor_bg,"foreground":editor_fg,"selection":hexcolor(colors.get("SELECTION_BACKGROUND")) or selection,"line":hexcolor(colors.get("CARET_ROW_COLOR")) or hover,"cursor":hexcolor(colors.get("CARET_COLOR")) or accent,"lineNumber":readable(hexcolor(colors.get("LINE_NUMBERS_COLOR")) or muted,editor_bg,3),"indent":hexcolor(colors.get("INDENT_GUIDE")) or border}
    terminal_bg=hexcolor(colors.get("CONSOLE_BACKGROUND_KEY")) or editor_bg
    terminal_fg=readable(hexcolor(attrs.get("CONSOLE_NORMAL_OUTPUT",{}).get("FOREGROUND")) or editor_fg,terminal_bg)
    terminal={"background":terminal_bg,"foreground":terminal_fg,"cursor":editor["cursor"],"cursor-accent":terminal_bg,"selection-background":editor["selection"],"selection-inactive-background":editor["selection"],"scrollbar-slider-background":border+"80","scrollbar-slider-hover-background":border+"b0","scrollbar-slider-active-background":border,"overview-ruler-border":"#00000000"}
    for name,attribute,fallback in [("black","BLACK",border),("red","RED","#ce5e5e"),("green","GREEN","#30a25e"),("yellow","YELLOW","#d09136"),("blue","BLUE",accent),("magenta","MAGENTA",syntax["keyword"]),("cyan","CYAN",syntax["type"]),("white","GRAY",terminal_fg),("bright-black","DARKGRAY",muted),("bright-red","RED_BRIGHT","#ff6e6e"),("bright-green","GREEN_BRIGHT","#69ff94"),("bright-yellow","YELLOW_BRIGHT","#ffffa5"),("bright-blue","BLUE_BRIGHT",accent),("bright-magenta","MAGENTA_BRIGHT",syntax["keyword"]),("bright-cyan","CYAN_BRIGHT",syntax["type"]),("bright-white","WHITE",terminal_fg)]:
        terminal[name]=readable(hexcolor(attrs.get("CONSOLE_"+attribute+"_OUTPUT",{}).get("FOREGROUND")) or fallback,terminal_bg,3)
    p={"background":bg,"foreground":fg,"rail":rail,"hover":hover,"selection":selection,"border":border,"muted":muted,"accent":accent,"accentForeground":primary_text,"syntax":syntax,"editor":editor,"terminal":terminal}
    palettes[theme_id]=p
    catalog.append({"id":theme_id,"name":data["name"],"labelZh":("Islands · " if islands else "Falcon · ")+NAMES[key],"mode":mode,"variant":"islands" if islands else "classic","background":bg,"foreground":fg,"accent":accent,"rail":rail})
    for source_file in (file,scheme_path):
        source_hashes[str(source_file.relative_to(SOURCE)).replace("\\","/")]=hashlib.sha256(source_file.read_bytes()).hexdigest()
    mapping={"background":bg,"foreground":fg,"card":bg,"card-foreground":fg,"popover":bg,"popover-foreground":fg,"primary":accent,"primary-foreground":primary_text,"secondary":hover,"secondary-foreground":fg,"muted":bg,"muted-foreground":muted,"settings-rail":rail,"settings-tile":bg,"settings-tile-hover":hover,"settings-active":selection,"control-surface":bg,"segmented-track":hover,"segmented-selected":selection,"accent":hover,"accent-foreground":fg,"border":border,"input":border,"ring":accent,"sidebar-bg":rail,"hub-canvas":rail,"chip-bg":hover,"chip-bg-hover":selection,"send-disabled-bg":hover,"chat-user-bg":hover,"chat-user-fg":fg,"chat-assistant-bg":bg,"chat-assistant-fg":fg,"chat-tool-bg":bg,"chat-tool-border":border,"chat-thinking-bg":rail,"chat-thinking-border":border,"chat-success":terminal["green"],"chat-error":terminal["red"],"chat-running":accent,"tool-bash-accent":terminal["green"],"tool-file-accent":terminal["blue"],"tool-search-accent":terminal["yellow"],"tool-list-accent":accent,"checkpoint-accent":muted,"checkpoint-icon-bg":hover,"checkpoint-icon-fg":fg}
    tokens={k:hsl(v) for k,v in mapping.items()}
    for status,source_name,fallback in [("destructive","error",terminal["red"]),("success","success",terminal["green"]),("warning","warning",terminal["yellow"]),("info","info",terminal["blue"])]:
        value=color(source_name,fallback)
        surface=blend(value,bg,.12 if dark else .06)
        value=readable(value,surface)
        tokens.update({status:value,status+"-foreground":max(("#ffffff","#111111"),key=lambda c:contrast(c,value)),status+"-surface":surface})
    tokens.update({"tool-card-bg":hsl(bg)+" / 0.9","tool-card-border":hsl(border)+" / 0.7","checkpoint-bg":hsl(bg)+" / 0.9","checkpoint-border":hsl(border)+" / 0.7","warning-tint":tokens["warning"],"control-checked":accent,"control-thumb":primary_text,"search-highlight":terminal["yellow"]+"40","drop-indicator":accent,"compaction":accent,"compaction-icon":accent,"compaction-foreground":readable(accent,bg),"overlay":"#00000066","surface-subtle":fg+"08","glass":bg+"e6","glass-border":border+"60","glass-border-strong":border,"glass-fill":hover+"80","glass-highlight":fg+"12","media-frame":bg,"media-canvas":rail,"ui-color-1677ff":accent})
    for terminal_mode in ("light","dark"):
        tokens.update({f"terminal-{terminal_mode}-{k}":v for k,v in terminal.items()})
    selector=f':root[data-color-theme="{theme_id}"]'
    css.append(block(selector,tokens))
    boot_css.append(block(selector,{"background":hsl(bg),"foreground":hsl(fg)}))

# Refuse to label modified/different upstream sources as the pinned revision.
manifest_path = ROOT / "crates/agent-ui/src/lib/appearance/falcon-source.json"
if manifest_path.exists():
    pinned = json.loads(manifest_path.read_text(encoding="utf-8"))
    if pinned["revision"] == REVISION and pinned["files"] != source_hashes:
        raise ValueError("Source files do not match the recorded pinned Falcon revision")

catalog.sort(key=lambda t:(t["variant"]!="classic",t["mode"]!="light",t["id"]))
def write(relative,text):
    path=ROOT/relative
    path.parent.mkdir(parents=True,exist_ok=True)
    path.write_text(text,encoding="utf-8",newline="\n")
write("crates/agent-ui/src/lib/appearance/falcon.json",json.dumps(palettes,ensure_ascii=False,indent=2)+"\n")
write("crates/agent-ui/src/lib/appearance/falconCatalog.ts",'// Generated by scripts/generate-falcon-themes.py; pinned Falcon MIT palettes.\nexport const FALCON_THEMES = '+json.dumps(catalog,ensure_ascii=False,indent=2)+' as const;\n\nexport type FalconThemeId = (typeof FALCON_THEMES)[number]["id"];\nconst byId = new Map<string, (typeof FALCON_THEMES)[number]>(FALCON_THEMES.map(theme => [theme.id, theme]));\nexport function getFalconTheme(id: unknown) {\n  return typeof id === "string" ? byId.get(id) : undefined;\n}\n')
write("crates/agent-ui/src/styles/falcon.css","\n".join(css))
write("crates/agent-gui/public/third-party/falcon-LICENSE.txt",(SOURCE/"LICENSE").read_text(encoding="utf-8"))
write("crates/agent-ui/src/lib/appearance/falcon-source.json",json.dumps({"repository":"https://github.com/panxiaoan/falcon-jetbrains-themes","revision":REVISION,"license":"MIT","files":source_hashes},indent=2)+"\n")
# One generated allowlist also drives the inline pre-React boot script, without a network round trip.
index=ROOT/"crates/agent-gui/index.html"
html=index.read_text(encoding="utf-8")
boot='/* falcon-boot:start */\n        const falconModes = '+json.dumps({t["id"]:t["mode"] for t in catalog},separators=(",",":"))+';\n        /* falcon-boot:end */'
if '/* falcon-boot:start */' in html:
    html=re.sub(r'/\* falcon-boot:start \*/.*?/\* falcon-boot:end \*/',lambda _:boot,html,flags=re.S)
else:
    html=html.replace('let colorTheme = "default";','let colorTheme = "default";\n        '+boot)
style='/* falcon-boot-colors:start */\n'+"\n".join(boot_css)+'      /* falcon-boot-colors:end */'
if '/* falcon-boot-colors:start */' in html:
    html=re.sub(r'/\* falcon-boot-colors:start \*/.*?/\* falcon-boot-colors:end \*/',lambda _:style,html,flags=re.S)
else:
    html=html.replace('      html,\n', '      '+style+'\n      html,\n',1)
index.write_text(html,encoding="utf-8",newline="\n")
print(f"Generated {len(catalog)} Falcon themes from {REVISION}.")
